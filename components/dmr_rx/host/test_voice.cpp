static uint8_t g_frames[kNumFrames][7];

static uint32_t g_seed = 0x1234abcd;
static uint32_t rnd()
{
    g_seed ^= g_seed << 13;
    g_seed ^= g_seed >> 17;
    g_seed ^= g_seed << 5;
    return g_seed;
}

static double rms(const int16_t *p)
{
    double s = 0;
    for (int i = 0; i < N; i++)
        s += (double)p[i] * (double)p[i];
    return sqrt(s / N);
}
static int peak(const int16_t *p)
{
    int m = 0;
    for (int i = 0; i < N; i++)
        if (abs(p[i]) > m)
            m = abs(p[i]);
    return m;
}
static bool all_zero(const int16_t *p)
{
    return peak(p) == 0;
}

/* 49 bits, one per char (mbelib layout) */
static void unpack(const uint8_t b[7], char d[49])
{
    for (int i = 0; i < 49; i++)
        d[i] = (char)((b[i >> 3] >> (7 - (i & 7))) & 1);
}
/* replace the pitch parameter b0 (ambe_d[0..3], [37..39]) */
static void set_b0(uint8_t b[7], unsigned b0)
{
    static const int pos[7] = {0, 1, 2, 3, 37, 38, 39};
    for (int i = 0; i < 7; i++) {
        const uint8_t m = (uint8_t)(0x80u >> (pos[i] & 7));
        if ((b0 >> (6 - i)) & 1u)
            b[pos[i] >> 3] |= m;
        else
            b[pos[i] >> 3] &= (uint8_t)~m;
    }
}

static void decode_all(dmr_vocoder_t *v, int first, int count, int16_t *out)
{
    for (int k = 0; k < count; k++)
        dmr_vocoder_decode(v, g_frames[first + k], 0, 0, 1.0f, out + (size_t)k * N);
}

/* Comparison with the double precision reference */
static void test_reference(const int16_t *pcm)
{
    int bad_rms = 0, bad_snr = 0, active = 0;
    double worst_dev = 0, sig = 0, err = 0, worst_snr = 1e9;
    for (int k = 0; k < kNumFrames; k++) {
        const double ref = kRefRms10[k] / 10.0, got = rms(pcm + (size_t)k * N);
        const double dev = fabs(got - ref);
        if (dev > 0.02 * ref + 3.0)
            bad_rms++;
        if (ref > 0 && dev / ref > worst_dev)
            worst_dev = dev / ref;
        if (ref > 300.0)
            active++;
    }
    CHECK(active >= kNumFrames / 2, "%d of %d reference frames carry speech (RMS > 300)", active, (int)kNumFrames);
    CHECK(bad_rms == 0, "per frame RMS within 2 %% + 3 of the reference: %d of %d frames off, worst deviation %.4f %%",
          bad_rms, (int)kNumFrames, 100.0 * worst_dev);
    int maxdiff = 0;
    for (int j = 0; j < kNumPcm; j++) {
        const int16_t *p = pcm + (size_t)j * kPcmEvery * N;
        double s = 0, e = 0;
        for (int i = 0; i < N; i++) {
            const double d = (double)kRefPcm[j][i] - (double)p[i];
            s += (double)kRefPcm[j][i] * (double)kRefPcm[j][i];
            e += d * d;
            if (abs(kRefPcm[j][i] - p[i]) > maxdiff)
                maxdiff = abs(kRefPcm[j][i] - p[i]);
        }
        sig += s;
        err += e;
        if (s > N * 100.0 * 100.0) { /* frames with RMS > 100 */
            const double snr = e > 0 ? 10.0 * log10(s / e) : 200.0;
            if (snr < worst_snr)
                worst_snr = snr;
            if (snr < 40.0)
                bad_snr++;
        }
    }
    const double snr = err > 0 ? 10.0 * log10(sig / err) : 200.0;
    CHECK(snr >= 50.0, "SNR against the reference PCM of %d frames: %.1f dB (max abs sample difference %d)", (int)kNumPcm,
          snr, maxdiff);
    CHECK(bad_snr == 0, "every reference frame with RMS > 100 reaches 40 dB: worst %.1f dB", worst_snr);
    CHECK(maxdiff <= 64, "max abs sample difference to the reference PCM: %d", maxdiff);
}

/* Same input, same output: second instance, reset, internal interface */
static void test_determinism(const int16_t *pcm)
{
    static int16_t a[kNumFrames * N], b[kNumFrames * N];
    dmr_vocoder_t *v1 = dmr_vocoder_create(), *v2 = dmr_vocoder_create();
    CHECK(v1 && v2, "dmr_vocoder_create");
    if (!v1 || !v2)
        return;

    decode_all(v2, 0, kNumFrames, a);
    CHECK(memcmp(a, pcm, sizeof(a)) == 0, "a second instance produces identical PCM");

    /* two instances used by turns on different streams (two timeslots) */
    enum { kOff = 37, kCnt = kNumFrames - kOff };
    dmr_vocoder_reset(v1);
    dmr_vocoder_reset(v2);
    for (int k = 0; k < kCnt; k++) {
        dmr_vocoder_decode(v1, g_frames[k], 0, 0, 1.0f, a + (size_t)k * N);
        dmr_vocoder_decode(v2, g_frames[kOff + k], 0, 0, 1.0f, b + (size_t)k * N);
    }
    CHECK(memcmp(a, pcm, (size_t)kCnt * N * sizeof(int16_t)) == 0, "instance 1 unaffected by instance 2 used in turns");
    dmr_vocoder_reset(v1);
    decode_all(v1, kOff, kCnt, a);
    CHECK(memcmp(a, b, (size_t)kCnt * N * sizeof(int16_t)) == 0, "instance 2 unaffected by instance 1 used in turns");

    /* reset in the middle of a call */
    decode_all(v1, 20, 50, a);
    dmr_vocoder_reset(v1);
    decode_all(v1, 0, kNumFrames, a);
    CHECK(memcmp(a, pcm, sizeof(a)) == 0, "identical PCM after dmr_vocoder_reset");

    /* internal interface (what dmr_rx uses): caller allocated state */
    const size_t sz = vocoder_size();
    CHECK(sz > 0 && sz <= 8192, "vocoder_size() = %zu bytes", sz);
    Vocoder *iv = (Vocoder *)malloc(sz);
    CHECK(iv != nullptr, "allocate Vocoder");
    if (iv) {
        memset(iv, 0xa5, sz); /* vocoder_init must not depend on the previous content */
        vocoder_init(iv);
        for (int k = 0; k < kNumFrames; k++) {
            char d[49];
            unpack(g_frames[k], d);
            vocoder_decode(iv, d, 0, false, 1.0f, a + (size_t)k * N);
        }
        CHECK(memcmp(a, pcm, sizeof(a)) == 0, "vocoder_init/vocoder_decode identical to dmr_vocoder_*");
        vocoder_init(iv);
        for (int k = 0; k < 40; k++) {
            char d[49];
            unpack(g_frames[k], d);
            vocoder_decode(iv, d, 0, false, 1.0f, a + (size_t)k * N);
        }
        CHECK(memcmp(a, pcm, (size_t)40 * N * sizeof(int16_t)) == 0, "identical PCM after vocoder_init (call start)");
        free(iv);
    }
    dmr_vocoder_destroy(v1);
    dmr_vocoder_destroy(v2);
}

static void test_silence()
{
    dmr_vocoder_t *v = dmr_vocoder_create();
    if (!v)
        return;
    char d[49];
    unpack(kSilence49, d);
    const int b0 = (d[0] << 6) | (d[1] << 5) | (d[2] << 4) | (d[3] << 3) | (d[37] << 2) | (d[38] << 1) | d[39];
    CHECK(b0 == 124 || b0 == 125, "silence frame has b0 = %d", b0);
    int pk = 0;
    double r = 0;
    for (int k = 0; k < 50; k++) {
        int16_t p[N];
        dmr_vocoder_decode(v, kSilence49, 0, 0, 1.0f, p);
        if (peak(p) > pk)
            pk = peak(p);
        if (rms(p) > r)
            r = rms(p);
    }
    CHECK(pk <= 64 && r <= 16.0, "50 silence frames decode to near silence: peak %d, max frame RMS %.2f", pk, r);

    /* silence after speech: fades out within a few frames */
    int16_t p[N];
    for (int k = 0; k < 40; k++)
        dmr_vocoder_decode(v, g_frames[k], 0, 0, 1.0f, p);
    for (int k = 0; k < 4; k++)
        dmr_vocoder_decode(v, kSilence49, 0, 0, 1.0f, p);
    CHECK(peak(p) <= 64, "silence frames after speech: peak %d in the 4th frame", peak(p));
    dmr_vocoder_destroy(v);
}

